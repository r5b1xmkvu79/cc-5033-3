"""Synthetic reference material.

Generates a known progressive ground truth containing the four structures an
archive deinterlacer must handle, then emulates interlaced camera capture by
subsampling fields at twice the frame rate. Because the ground truth is
generated by us, the benchmark can score motion smoothness, comb residue and
detail loss against exact reference frames instead of eyeballing a player.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

from . import ffmpeg_io, fields as F

WIDTH, HEIGHT = 320, 240
GROUND_FPS = 50.0          # field rate of the emulated interlaced signal
SOURCE_FPS = 25.0          # frame rate after fields are packed two per frame
DURATION = 2.0


def _font() -> ImageFont.ImageFont:
    for name in ("DejaVuSans-Bold.ttf", "DejaVuSans.ttf"):
        try:
            return ImageFont.truetype(name, 22)
        except OSError:
            continue
    return ImageFont.load_default()


def _render_progressive_frame(t: float, k: int) -> np.ndarray:
    """Render one ground-truth frame at ground time t (seconds)."""
    img = Image.new("RGB", (WIDTH, HEIGHT), (18, 18, 24))
    draw = ImageDraw.Draw(img)
    font = _font()

    # 1. Horizontally moving vertical stripes: translation reveals temporal
    #    order mistakes immediately (motion runs right at constant speed).
    stripe_speed = 60.0  # px/s
    shift = stripe_speed * t
    for x in range(-40, WIDTH + 40, 24):
        x0 = int((x + shift) % (WIDTH + 48) - 24)
        draw.rectangle([x0, 10, x0 + 10, 90], fill=(230, 60, 60))

    # 2. Fine text moving at a different speed: thin strokes expose detail
    #    loss and any residual combing on glyph edges.
    text = "ARCHIVE 1973"
    text_shift = int(35.0 * t) % (WIDTH + 160)
    draw.text((text_shift - 80, 104), text, fill=(240, 240, 220), font=font)

    # 3. Diagonal line drifting sideways: staircase/edge behavior.
    diag_origin = int(20.0 * t)
    draw.line(
        [(diag_origin, 150), (diag_origin + 180, 232)],
        fill=(90, 200, 255),
        width=2,
    )

    # 4. Static pattern, never moves: must come back pixel-perfect in still
    #    regions and is the reference for detail retention.
    for x in range(250, 310, 4):
        draw.line([(x, 150), (x, 232)], fill=(200, 200, 200))
    for y in range(150, 232, 4):
        draw.line([(250, y), (310, y)], fill=(120, 120, 120))
    draw.rectangle([252, 152, 266, 166], outline=(255, 215, 80), width=1)

    return np.asarray(img, dtype=np.uint8).copy()


def make_ground_truth(
    out_dir: str | Path, ffmpeg: str | None = None
) -> tuple[Path, list[np.ndarray]]:
    """Render every field-rate ground-truth frame and encode the truth video."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    n = int(round(GROUND_FPS * DURATION))
    frames = [_render_progressive_frame(k / GROUND_FPS, k) for k in range(n)]
    path = out_dir / "ground_truth_progressive.mp4"
    ffmpeg_io.encode_frames(
        iter(frames), path, WIDTH, HEIGHT, GROUND_FPS, ffmpeg=ffmpeg, crf=14
    )
    return path, frames


def emulate_interlaced(
    ground_truth: list[np.ndarray], field_order: str
) -> list[np.ndarray]:
    """Pack field-rate ground truth into interlaced frames.

    Consecutive ground-truth frames become the two fields of one interlaced
    frame, so each field keeps its own sampling instant. TFF puts the earlier
    instant on even rows, BFF on odd rows.
    """
    if field_order not in (F.TFF, F.BFF):
        raise ValueError("field_order must be 'tff' or 'bff'")
    pairs = len(ground_truth) // 2
    interlaced = []
    for k in range(pairs):
        earlier = ground_truth[2 * k]
        later = ground_truth[2 * k + 1]
        frame = np.empty_like(earlier)
        if field_order == F.TFF:
            frame[0::2] = earlier[0::2]
            frame[1::2] = later[1::2]
        else:
            frame[1::2] = earlier[1::2]
            frame[0::2] = later[0::2]
        interlaced.append(frame)
    return interlaced


def write_interlaced(
    interlaced: list[np.ndarray],
    out_dir: str | Path,
    field_order: str,
    ffmpeg: str | None = None,
) -> Path:
    """Encode the emulated capture, marking the declared field order.

    Note x264 MBAFF is intentionally avoided: we write raw interlaced frames
    and record the order in a sidecar so decoding returns exactly the rows we
    packed, which keeps the benchmark deterministic.
    """
    out_dir = Path(out_dir)
    path = out_dir / f"synthetic_interlaced_{field_order}.mp4"
    ffmpeg_io.encode_frames(
        iter(interlaced), path, WIDTH, HEIGHT, SOURCE_FPS, ffmpeg=ffmpeg, crf=14
    )
    ffmpeg_io.write_manifest(
        {
            "video_file": path.name,
            "declared_field_order": field_order,
            "source_fps": SOURCE_FPS,
            "ground_truth_fps": GROUND_FPS,
            "frame_count": len(interlaced),
            "note": "raw interlaced rows; field order recorded here, not via MBAFF",
        },
        out_dir / f"synthetic_interlaced_{field_order}.json",
    )
    return path


def generate_reference_set(
    out_dir: str | Path, ffmpeg: str | None = None
) -> dict:
    """Build ground truth plus both TFF and BFF emulated interlaced clips."""
    out_dir = Path(out_dir)
    truth_path, truth = make_ground_truth(out_dir, ffmpeg)
    outputs = {"ground_truth": str(truth_path), "clips": {}}
    for order in (F.TFF, F.BFF):
        interlaced = emulate_interlaced(truth, order)
        clip = write_interlaced(interlaced, out_dir, order, ffmpeg)
        outputs["clips"][order] = {
            "path": str(clip),
            "frames": len(interlaced),
        }
    return outputs
